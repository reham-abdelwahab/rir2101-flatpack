#!/usr/bin/env python3
"""results.json -> results.md (tables only; every number is read from results.json, none typed by hand)."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
r = json.loads((HERE / "results.json").read_text())
RUNS = ["vtracer_default_binary", "vtracer_best_effort", "ours_default", "ours_dark_on_light"]
LABEL = {"vtracer_default_binary": "VTracer default (binary)", "vtracer_best_effort": "VTracer best effort",
         "ours_default": "Ours, UI default (Remove background)", "ours_dark_on_light": "Ours, Dark on light"}


def f(v, n=4):
    return "—" if v is None else (f"{v:.{n}f}" if isinstance(v, float) else str(v))


L = ["# VTracer vs FlatPack tracer — measured results", "",
     f"Generated by `make_report.py` from `results.json` (run started {r['meta']['run_started']}). "
     f"Leak rule: {r['meta']['leak_rule']}. All geometry in mm at 10 px/mm (image frame).", "",
     "## Cases with exact ground truth", "",
     "| Case | Pipeline | IoU | Area error % | Hausdorff (mm) | Nodes (all paths) | Paths | Background leak | Our QA gate fires |",
     "|---|---|---|---|---|---|---|---|---|"]
for case, e in r["cases"].items():
    if not e.get("ground_truth"):
        continue
    for k in RUNS:
        v = e["runs"].get(k, {})
        if "error" in v:
            L.append(f"| {case} | {LABEL[k]} | ERROR: {v['error']} |||||||"); continue
        m = v["metrics_all_paths"]
        qa = v.get("traceQA") or v.get("would_trip_our_gate") or {}
        leak = "yes " + str(m["leak_pieces_mm2"]) + " mm²" if m["background_leak"] else "no"
        L.append(f"| {case} | {LABEL[k]} | {f(m['iou'], 5)} | {f(m['area_error_pct'], 3)} | {f(m['hausdorff_boundary_mm'], 3)} | "
                 f"{v['nodes_all']} | {v['n_paths']} | {leak} | {'yes' if qa.get('suspect') else 'no'}{'' if k.startswith('ours') else ' (rule applied offline)'} |")
L += ["", "## Case 3 — room picture (H14), no outline ground truth", "",
      "| Pipeline | Paths | Nodes | Outline bbox / picture | Edges touched | Room/background warning | Printing blocked | What was outlined (see out/room_h14__overlay.png) |",
      "|---|---|---|---|---|---|---|---|"]
e = r["cases"].get("room_h14", {})
for k in RUNS:
    v = e.get("runs", {}).get(k)
    if not v:
        continue
    if "error" in v:
        L.append(f"| {LABEL[k]} | ERROR: {v['error']} |||||||"); continue
    if k.startswith("ours"):
        qa = v["traceQA"]
        warn = "yes" if qa["suspect"] else "no"
        blocked = "yes — until the student ticks “only the furniture”" if v["print_blocked_until_student_confirms"] else "no"
        bb, ed = qa["bboxFrac"], qa["edges"]
    else:
        qa = v["would_trip_our_gate"]
        warn = "no (VTracer has no such check)"
        blocked = "no (VTracer has no print step)"
        bb, ed = qa["bboxFrac"], qa["edges"]
    L.append(f"| {LABEL[k]} | {v['n_paths']} | {v['nodes_all']} | {f(bb, 3)} | {ed} | {warn} | {blocked} | {{{{{k}}}}} |")
L += ["", "## Wall-clock per trace (s, includes I/O; ours includes page.evaluate round-trip)", "",
      "| Case | " + " | ".join(LABEL[k] for k in RUNS) + " |", "|---|" + "---|" * len(RUNS)]
for case, e in r["cases"].items():
    L.append(f"| {case} | " + " | ".join(f(e["runs"].get(k, {}).get("wall_s"), 3) for k in RUNS) + " |")
OBS = {  # visual reading of out/room_h14__overlay.png by the analyst (not computed)
    "vtracer_default_binary": "every dark stroke: page frames, room lines, dashed guides, curtains, chair, red X, pencil, ruler",
    "vtracer_best_effort": "outer page edge, inner rounded frame, chair + red X/circle, pencil, ruler",
    "ours_default": "the inner rounded frame of the handout card (the whole room drawing, filled)",
    "ours_dark_on_light": "the red circle + X with the chair inside it (not the chair alone)",
}
txt = "\n".join(L) + "\n"
for k, v in OBS.items():
    txt = txt.replace("{{" + k + "}}", v)
txt += (HERE / "notes.md").read_text() if (HERE / "notes.md").exists() else ""
(HERE / "results.md").write_text(txt)
print(txt)
